ScootLocale.keys = { ['~INPUT_CONTEXT~'] = 'E', ['~INPUT_DETONATE~'] = 'G', ['~INPUT_FRONTEND_ACCEPT~'] = 'ENTER' }

function ScootLocale.Resolve()
    if ScootLocale.current then return ScootLocale.current end
    local name
    if type(Config) == 'table' then
        if type(Config.Language) == 'string' and Config.Language ~= 'auto' then name = Config.Language
        elseif type(Config.Locale) == 'string' then name = Config.Locale end
    end
    if not name and type(GetConvar) == 'function' then
        for _, convar in ipairs({ 'scoot_locale', 'ox:locale', 'esx:locale', 'qb_locale' }) do
            local ok, value = pcall(GetConvar, convar, '')
            if ok and type(value) == 'string' and value ~= '' then name = value:sub(1, 2);break end
        end
    end
    name = type(name) == 'string' and name:lower() or 'en'
    local resolved = ScootLocale.data[name] and name or 'en'
    ScootLocale.current = resolved
    return resolved
end

function ScootText(key, ...)
    local table_ = ScootLocale.data[ScootLocale.Resolve()] or ScootLocale.data.en
    local value = table_[key]
    if value == nil then value = ScootLocale.data.en[key] end
    if type(value) ~= 'string' then return key end
    if select('#', ...) == 0 then return value end
    local ok, formatted = pcall(string.format, value, ...)
    return ok and formatted or value
end

function ScootPromptKey(text)
    if type(text) ~= 'string' then return end
    local token, label = text:match('^(~INPUT_%u+~)%s*(.*)$')
    if not token then return nil, text end
    return ScootLocale.keys[token], label
end
